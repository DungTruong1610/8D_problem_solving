/**
 * Export all eight 8D step prompts and schemas as an English Markdown reference.
 *
 * Read DEFAULT_STEP_PROMPTS directly so the exported payloads stay aligned with
 * the application defaults. The runtime uses combinedPrompt ?? systemPrompt;
 * combinedPrompt replaces systemPrompt rather than extending it.
 *
 * Run npm run export:prompts, or provide an optional destination:
 * node --import ./node_modules/tsx/dist/loader.mjs scripts/export-step-prompts.mjs [destination]
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const { DEFAULT_STEP_PROMPTS } = await import('../srv/src/domain/eightd/precedent/defaults.ts');

const out = resolve(process.argv[2] ?? 'docs/8d-step-prompts.md');

const lines = [
    '# 8D Step Prompts',
    '',
    'Generated with `npm run export:prompts` - **do not edit this file manually**.',
    'Sources: `srv/src/domain/eightd/prompts.ts` (`DEFAULT_DISCIPLINE_GUIDE`) and',
    '`srv/src/domain/eightd/precedent/defaults.ts` (`STRUCTURED_CONFIG_OVERRIDES`).',
    '',
    '## Quick setup without manual pasting',
    '',
    'Start the backend, then run:',
    '',
    '```bash',
    'npm run push:prompts          # all eight steps',
    'npm run push:prompts -- D4    # D4 only',
    '```',
    '',
    'This command replaces the selected step configuration with the code defaults exported here.',
    'Manual AI Settings changes for those steps will be lost. The command asks for confirmation.',
    '',
    '## Manual setup: populate all three fields for each step',
    '',
    'The prompt alone is not sufficient. Field-length limits, allowed values,',
    'array item structure and field descriptions are defined in the JSON schemas.',
    'Those schemas constrain structured output, while the prompt provides guidance.',
    'Pasting only the prompt can leave important configuration changes unapplied.',
    '',
    'The runtime reads `combinedPrompt ?? systemPrompt`, so **`combinedPrompt`',
    'replaces `systemPrompt`** instead of extending it. Saving into the wrong field',
    'can succeed without changing the prompt used at runtime.',
    '',
    '| Step | Fields to populate | Prompt word count |',
    '| - | - | - |',
];

for (const step of DEFAULT_STEP_PROMPTS) {
    const field = step.combinedPrompt ? 'combinedPrompt' : 'systemPrompt';
    const text = (step.combinedPrompt ?? step.systemPrompt ?? '').trim();
    const boxes = [field, step.inputSchemaJson && 'inputSchemaJson', step.formSchemaJson && 'formSchemaJson']
        .filter(Boolean).map((name) => `\`${name}\``).join(' + ');
    lines.push(`| ${step.stepCode} - ${step.label} | ${boxes} | ${text.split(/\s+/).length} |`);
}
lines.push('');

for (const step of DEFAULT_STEP_PROMPTS) {
    const field = step.combinedPrompt ? 'combinedPrompt' : 'systemPrompt';
    const text = (step.combinedPrompt ?? step.systemPrompt ?? '').trim();
    lines.push(
        '',
        `## ${step.stepCode} - ${step.label}`,
        '',
        `${step.description}`,
        '',
        `### 1. Prompt - field \`${field}\``,
        '',
        `Row \`stepCode = '${step.stepCode}'\` in the \`StepPrompts\` table.`,
        '',
        '```text',
        text,
        '```',
        '',
    );

    // Export schemas alongside the prompt so manual configuration preserves the
    // field limits, allowed values and structured-output contract.
    for (const [label, json] of [
        ['Data Schema', step.inputSchemaJson],
        ['Form Editor', step.formSchemaJson],
    ]) {
        if (!json) continue;
        lines.push(
            `### ${label === 'Data Schema' ? 2 : 3}. ${label} - field \`${label === 'Data Schema' ? 'inputSchemaJson' : 'formSchemaJson'}\``,
            '',
            '```json',
            json.trim(),
            '```',
            '',
        );
    }
}

writeFileSync(out, lines.join('\n'), 'utf8');
console.log(`OK: ${DEFAULT_STEP_PROMPTS.length} steps -> ${out}`);
